# -*- coding: utf-8 -*-
"""Aggregate migration status files into migration/TASK-LEDGER.md and a summary."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIG = ROOT / "migration"
STATUS = MIG / "status"


def main():
    inventory = json.loads((MIG / "inventory.json").read_text(encoding="utf-8"))
    rows = {}
    if STATUS.is_dir():
        for p in STATUS.glob("*.json"):
            try:
                d = json.loads(p.read_text(encoding="utf-8"))
                rows[d["task"]] = d
            except Exception:
                pass
    counts = {}
    lines = ["# TASK MIGRATION LEDGER", "",
             "> Source: runhey/OnmyojiAutoScript@dev (read-only). Status: ⬜ pending / 🔄 in progress / ✅ implemented / ⛔ blocked.",
             "> Generated by scripts/migrate_status.py from migration/status/*.json.", "",
             "| # | Task | Group | Script lines | Assets | Status | Evidence / gaps |",
             "|---|---|---|---:|---:|---|---|"]
    for i, r in enumerate(inventory, 1):
        d = rows.get(r["task"], {})
        status = d.get("status", "⬜")
        counts[status] = counts.get(status, 0) + 1
        note = str(d.get("evidence") or "")
        gaps = d.get("gaps") or []
        if gaps:
            note += " GAPS: " + "; ".join(str(g) for g in gaps)
        note = note.replace("|", "/")[:240]
        lines.append(f"| {i} | {r['task']} | {r['group']} | {r['script_lines']} | {r['assets']} | {status} | {note} |")
    (MIG / "TASK-LEDGER.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    summary = {"total": len(inventory), "counts": counts}
    (MIG / "STATUS.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary, ensure_ascii=False))
    for task, d in sorted(rows.items()):
        print(f"{task}: {d.get('status')} {d.get('evidence','')}")


if __name__ == "__main__":
    main()
